#!/usr/bin/env bash
#
# Control de Red v9 - Docker Quickstart
# One-command local setup: Database + Redis + Backend
#

set -e  # Exit on error

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Emojis
ROCKET="🚀"
CHECK="✅"
CROSS="❌"
WARN="⚠️"
INFO="ℹ️"

echo ""
echo -e "${BLUE}${ROCKET} Control de Red v9 - Docker Quickstart${NC}"
echo "=========================================="
echo ""

# ==================== PRE-CHECKS ====================

echo -e "${INFO} Verificando requisitos..."
echo ""

# Check Docker installed
if ! command -v docker &> /dev/null; then
    echo -e "${CROSS} ${RED}Docker no está instalado${NC}"
    echo ""
    echo "Instalar Docker:"
    echo "  Linux: https://docs.docker.com/engine/install/"
    echo "  macOS: https://docs.docker.com/desktop/install/mac-install/"
    echo "  Windows: https://docs.docker.com/desktop/install/windows-install/"
    exit 1
fi
echo -e "${CHECK} Docker instalado: $(docker --version)"

# Check Docker Compose (v2 plugin or standalone)
if docker compose version &> /dev/null; then
    COMPOSE_CMD="docker compose"
    echo -e "${CHECK} Docker Compose plugin: $(docker compose version)"
elif command -v docker-compose &> /dev/null; then
    COMPOSE_CMD="docker-compose"
    echo -e "${CHECK} Docker Compose standalone: $(docker-compose --version)"
else
    echo -e "${CROSS} ${RED}Docker Compose no está instalado${NC}"
    echo ""
    echo "Instalar Docker Compose:"
    echo "  https://docs.docker.com/compose/install/"
    exit 1
fi

# Check Docker daemon running
if ! docker ps &> /dev/null; then
    echo -e "${CROSS} ${RED}Docker daemon no está corriendo${NC}"
    echo ""
    echo "Iniciar Docker:"
    echo "  Linux: sudo systemctl start docker"
    echo "  macOS/Windows: Abrir Docker Desktop"
    exit 1
fi
echo -e "${CHECK} Docker daemon corriendo"

echo ""
echo -e "${INFO} Requisitos cumplidos. Procediendo con setup..."
echo ""

# ==================== ENVIRONMENT ====================

# Generate .env if doesn't exist
if [ ! -f backend/.env ]; then
    echo -e "${INFO} Generando backend/.env con valores por defecto..."
    
    # Generate random secrets
    SECRET_KEY=$(openssl rand -hex 32 2>/dev/null || python3 -c "import secrets; print(secrets.token_hex(32))")
    JWT_SECRET_KEY=$(openssl rand -hex 32 2>/dev/null || python3 -c "import secrets; print(secrets.token_hex(32))")
    
    cat > backend/.env << EOF
# Control de Red - Environment Variables (Local Development)
# Generated by quickstart.sh on $(date)

# App Config
APP_NAME=control-red
DEBUG=true
LOG_LEVEL=INFO
VERSION=9.0.0-dev.13

# Security (Generated)
SECRET_KEY=${SECRET_KEY}
JWT_SECRET_KEY=${JWT_SECRET_KEY}

# Database (Docker Compose)
DATABASE_URL=postgresql+asyncpg://control_red_user:control_red_pass@postgres:5432/control_red

# Redis (Docker Compose)
REDIS_URL=redis://redis:6379/0

# Telegram Bot (Optional - configure later)
# TELEGRAM_BOT_TOKEN=your_token_here

# Sentry (Optional)
# SENTRY_DSN=

# CORS (Local development)
ALLOWED_ORIGINS=http://localhost:8000,http://127.0.0.1:8000
EOF
    
    echo -e "${CHECK} backend/.env creado"
else
    echo -e "${INFO} backend/.env ya existe, usando existente"
fi

echo ""

# ==================== DOCKER COMPOSE ====================

echo -e "${ROCKET} Levantando servicios con Docker Compose..."
echo ""

# Stop any existing containers
$COMPOSE_CMD down 2>/dev/null || true

# Build and start services
$COMPOSE_CMD up -d --build

echo ""
echo -e "${INFO} Esperando a que los servicios estén listos..."
echo ""

# Wait for PostgreSQL
echo -n "  PostgreSQL: "
for i in {1..30}; do
    if docker exec control-red-v9-dev-postgres-1 pg_isready -U control_red_user &>/dev/null 2>&1 || \
       docker exec postgres pg_isready -U control_red_user &>/dev/null 2>&1; then
        echo -e "${GREEN}READY${NC}"
        break
    fi
    if [ $i -eq 30 ]; then
        echo -e "${RED}TIMEOUT${NC}"
        echo ""
        echo -e "${WARN} PostgreSQL no respondió en 30s. Ver logs:"
        echo "    $COMPOSE_CMD logs postgres"
        exit 1
    fi
    sleep 1
done

# Wait for Redis
echo -n "  Redis: "
for i in {1..30}; do
    if docker exec control-red-v9-dev-redis-1 redis-cli ping &>/dev/null 2>&1 || \
       docker exec redis redis-cli ping &>/dev/null 2>&1; then
        echo -e "${GREEN}READY${NC}"
        break
    fi
    if [ $i -eq 30 ]; then
        echo -e "${RED}TIMEOUT${NC}"
        echo ""
        echo -e "${WARN} Redis no respondió en 30s. Ver logs:"
        echo "    $COMPOSE_CMD logs redis"
        exit 1
    fi
    sleep 1
done

# Wait for Backend (health check)
echo -n "  Backend: "
for i in {1..60}; do
    if curl -sf http://localhost:8000/ &>/dev/null; then
        echo -e "${GREEN}READY${NC}"
        break
    fi
    if [ $i -eq 60 ]; then
        echo -e "${RED}TIMEOUT${NC}"
        echo ""
        echo -e "${WARN} Backend no respondió en 60s. Ver logs:"
        echo "    $COMPOSE_CMD logs backend"
        exit 1
    fi
    sleep 1
done

echo ""

# ==================== HEALTH CHECKS ====================

echo -e "${CHECK} ${GREEN}Todos los servicios están corriendo!${NC}"
echo ""

# Backend health check
BACKEND_HEALTH=$(curl -s http://localhost:8000/ | python3 -m json.tool 2>/dev/null || echo '{"error": "invalid json"}')
echo "📊 Backend health check:"
echo "${BACKEND_HEALTH}" | sed 's/^/  /'
echo ""

# ==================== SUCCESS ====================

echo "=========================================="
echo -e "${CHECK} ${GREEN}Setup completado exitosamente!${NC}"
echo "=========================================="
echo ""
echo "🌐 Backend disponible en:"
echo "    http://localhost:8000"
echo ""
echo "📖 Documentación API (Swagger):"
echo "    http://localhost:8000/docs"
echo ""
echo "🔧 Comandos útiles:"
echo ""
echo "  Ver logs:"
echo "    $COMPOSE_CMD logs -f"
echo ""
echo "  Ver logs de un servicio:"
echo "    $COMPOSE_CMD logs -f backend"
echo "    $COMPOSE_CMD logs -f postgres"
echo "    $COMPOSE_CMD logs -f redis"
echo ""
echo "  Reiniciar servicios:"
echo "    $COMPOSE_CMD restart"
echo ""
echo "  Detener todo:"
echo "    $COMPOSE_CMD down"
echo ""
echo "  Detener y eliminar datos:"
echo "    $COMPOSE_CMD down -v"
echo ""
echo "🤖 Configurar Telegram Bot:"
echo ""
echo "  1. Editar backend/.env:"
echo "     TELEGRAM_BOT_TOKEN=tu_token_aqui"
echo ""
echo "  2. Reiniciar backend:"
echo "     $COMPOSE_CMD restart backend"
echo ""
echo "  3. Configurar webhook (si usas túnel):"
echo "     curl -X POST https://api.telegram.org/bot<TOKEN>/setWebhook \\"
echo "       -d url=https://tu-url-publica.com/api/telegram/webhook"
echo ""
echo "📚 Documentación completa:"
echo "    https://github.com/halexespejo-cmd/control-red-v9-dev#readme"
echo ""
echo -e "${ROCKET} ${BLUE}¡Listo para usar!${NC}"
echo ""
